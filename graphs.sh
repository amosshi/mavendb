#!/bin/sh
#
# Dependency graphs of mavendb-loader and mavendb-api, generated from <module>/target/classes: run after 'compile'.
# Used by build.sh and the GitHub Actions workflows. Needs jdeps (JDK) and dot (Graphviz).
#
# The graphs are embedded in the javadoc of each module's package, the home page of the module's javadoc.
# The javadoc plugin copies <module>/target/javadoc-resources (its javadocDirectory) into the javadoc output.
# Also writes the README.md of each package folder, with the UML diagrams of its classes (see uml_readme).
set -e
cd "$(dirname "$0")"

# Runtime classpath of a module, to <module>/target/jdeps/classpath.txt
classpath() {
    ./mvnw -q -B -ntp -pl "$1" dependency:build-classpath -Dmdep.includeScope=runtime -Dmdep.outputFile=target/jdeps/classpath.txt
}

# Jar graph of module $1 into the doc-files of package directory $2: module -> 3rd party jars -> their jars.
# -recursive adds the jar -> jar edges; JDK modules and "not found" (optional dependencies not on the classpath) are dropped.
jar_graph() {
    doc_files="$1/target/javadoc-resources/$2/doc-files"
    mkdir -p "$doc_files"
    jdeps --multi-release 25 --ignore-missing-deps -summary -recursive -dotoutput "$1/target/jdeps/jars" \
        --class-path "$(cat "$1/target/jdeps/classpath.txt")" "$1/target/classes"
    sed -e '/-> "\(java\|jdk\)\./d' -e '/-> "not found"/d' -e "s/\"classes\"/\"$1\"/" "$1/target/jdeps/jars/summary.dot" \
        | dot -Grankdir=LR -Nshape=box -Nfontname=Helvetica -Tsvg -o "$doc_files/jar-graph.svg"
}

# Module graph of module $1 into the doc-files of package directory $2: module -> 3rd party jars and JDK modules.
module_graph() {
    jdeps --multi-release 25 --ignore-missing-deps -summary -dotoutput "$1/target/jdeps/modules" \
        --class-path "$(cat "$1/target/jdeps/classpath.txt")" "$1/target/classes"
    sed -e "s/\"classes\"/\"$1\"/" -e 's/ ([a-z.]*)"/"/' "$1/target/jdeps/modules/summary.dot" \
        | dot -Grankdir=LR -Nshape=box -Nfontname=Helvetica -Tsvg -o "$1/target/javadoc-resources/$2/doc-files/module-graph.svg"
}

# UML index of module $1: a README.md in each package folder of src/main/java, which GitHub shows below the file list.
# It embeds the UML diagrams (umldoclet) of the package and of each class from the javadoc on the published site.
# The classes are listed from target/classes: Outer$Inner.class -> Outer.Inner, as umldoclet names the diagrams.
# The READMEs are committed; the Build workflow fails when they are not up to date.
SITE_APIDOCS=https://amosshi.github.io/mavendb/apidocs
uml_readme() {
    find "$1/target/classes" -name '*.class' ! -name 'package-info.class' -exec dirname {} \; | LC_ALL=C sort -u | while read -r dir; do
        pkg_dir="${dir#"$1/target/classes/"}"
        pkg=$(echo "$pkg_dir" | tr / .)
        url="$SITE_APIDOCS/$pkg_dir"
        {
            echo "# Package $pkg"
            echo
            echo "<!-- Generated by graphs.sh: do not edit -->"
            echo "UML diagrams from the [javadoc]($url/package-summary.html), generated by umldoclet."
            echo "The diagrams are those of the last site published from \`main\`."
            echo
            echo "## Package"
            echo
            echo "![Package $pkg]($url/package.svg)"
            echo
            echo "## Classes"
            for class in $(ls "$dir" | grep '\.class$' | grep -v '^package-info\.class$' | grep -v '\$[0-9]' | sed 's/\.class$//; s/\$/./g' | LC_ALL=C sort); do
                echo
                echo "### $class"
                echo
                echo "[Source](${class%%.*}.java) · [Javadoc]($url/$class.html)"
                echo
                echo "![UML of $class]($url/$class.svg)"
            done
        } > "$1/src/main/java/$pkg_dir/README.md"
    done
}

for module in mavendb-loader:org/mavendb/loader mavendb-api:org/mavendb/api; do
    classpath "${module%%:*}"
    jar_graph "${module%%:*}" "${module#*:}"
    module_graph "${module%%:*}" "${module#*:}"
    uml_readme "${module%%:*}"
done
